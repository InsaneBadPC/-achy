export interface AppReleaseInfo {
  hasUpdate: boolean;
  currentVersion: string;
  latestVersion: string;
  releaseName: string;
  releaseNotes: string;
  downloadUrl: string;
  publishedAt: string;
}

export const CURRENT_APP_VERSION = '1.0.4';
const DEFAULT_REPO = 'insanebad2/-achy';

/**
 * Compare two semver-like version strings (e.g., "1.0.4" vs "1.0.5")
 * Returns 1 if v2 > v1, -1 if v1 > v2, 0 if equal
 */
export function compareVersions(v1: string, v2: string): number {
  const clean1 = v1.replace(/^v/i, '').trim();
  const clean2 = v2.replace(/^v/i, '').trim();
  
  const p1 = clean1.split('.').map((n) => parseInt(n, 10) || 0);
  const p2 = clean2.split('.').map((n) => parseInt(n, 10) || 0);

  const len = Math.max(p1.length, p2.length);
  for (let i = 0; i < len; i++) {
    const num1 = p1[i] || 0;
    const num2 = p2[i] || 0;
    if (num2 > num1) return 1;
    if (num1 > num2) return -1;
  }
  return 0;
}

/**
 * Check GitHub Releases API for the latest published APK build
 */
export async function checkForGitHubUpdate(repoName: string = DEFAULT_REPO): Promise<AppReleaseInfo> {
  const defaultResult: AppReleaseInfo = {
    hasUpdate: false,
    currentVersion: CURRENT_APP_VERSION,
    latestVersion: CURRENT_APP_VERSION,
    releaseName: '',
    releaseNotes: '',
    downloadUrl: `https://github.com/${repoName}/releases`,
    publishedAt: '',
  };

  try {
    // 1. Try local version.json first (if generated by CI build)
    try {
      const localVerRes = await fetch('/version.json?t=' + Date.now());
      if (localVerRes.ok) {
        const localVer = await localVerRes.json();
        if (localVer && localVer.version) {
          defaultResult.currentVersion = localVer.version;
        }
      }
    } catch {
      // Ignore local fetch failure
    }

    // 2. Query GitHub Releases API
    const response = await fetch(`https://api.github.com/repos/${repoName}/releases/latest`, {
      headers: {
        Accept: 'application/vnd.github.v3+json',
      },
    });

    if (!response.ok) {
      return defaultResult;
    }

    const data = await response.json();
    const tagName = data.tag_name || data.name || '';
    const cleanTag = tagName.replace(/^v/i, '').trim();

    // Find APK asset
    let apkDownloadUrl = data.html_url;
    if (Array.isArray(data.assets)) {
      const apkAsset = data.assets.find(
        (a: { name: string; browser_download_url: string }) =>
          a.name.toLowerCase().endsWith('.apk')
      );
      if (apkAsset) {
        apkDownloadUrl = apkAsset.browser_download_url;
      }
    }

    const hasNewer = compareVersions(defaultResult.currentVersion, cleanTag) > 0;

    return {
      hasUpdate: hasNewer,
      currentVersion: defaultResult.currentVersion,
      latestVersion: cleanTag || defaultResult.currentVersion,
      releaseName: data.name || `Verze ${cleanTag}`,
      releaseNotes: data.body || 'Opravy chyb a vylepšení animací a postav.',
      downloadUrl: apkDownloadUrl,
      publishedAt: data.published_at || '',
    };
  } catch (err) {
    console.warn('Update check failed:', err);
    return defaultResult;
  }
}
